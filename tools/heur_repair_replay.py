"""Replay captured Rust repair inputs in Gurobi 13.0.3; run via tools/gurun.sh."""
import ctypes as c
import gzip
import hashlib
import json
import struct
import sys
from pathlib import Path

import gurobipy as gp

ROOT = Path(__file__).resolve().parent.parent
HASH = '8e87fca221fdffc922331c8619426031b3e72dfd419446422f88af0cb0e98f9c'


def same(a, b):
    return len(a) == len(b) and all(struct.pack('=d', x) == struct.pack('=d', y) for x, y in zip(a, b))


def replay(name, func):
    with gzip.open(ROOT / 'bench/oracle/mip_repair' / f'{name}.json.gz', 'rt') as f:
        fixture = json.load(f)
    d = fixture['model']
    n, m = len(d['obj']), len(d['rhs'])
    model = gp.Model()
    model.Params.OutputFlag = 0
    variables = model.addVars(n, lb=d['lb'], ub=d['ub'], obj=d['obj'], vtype=list(map(chr, d['vtype'])))
    model.ModelSense, model.ObjCon = d['sense'], d['objcon']
    model.update()
    rows = [[] for _ in range(m)]
    for j, (begin, length) in enumerate(zip(d['col_beg'], d['col_len'])):
        for k in range(begin, begin + length):
            rows[d['col_ind'][k]].append((j, d['col_val'][k]))
    for i, row in enumerate(rows):
        expr = gp.LinExpr([a for _, a in row], [variables[j] for j, _ in row])
        model.addLConstr(expr, chr(d['row_sense'][i]), d['rhs'][i])
    model.update()
    vs, cs = model.getVars(), model.getConstrs()
    assert same([r.RHS for r in cs], d['rhs']) and [r.Sense for r in cs] == list(map(chr, d['row_sense']))
    assert same([model.ObjCon], [d['objcon']]) and model.ModelSense == d['sense']
    api = c.pythonapi
    api.PyCapsule_GetName.argtypes, api.PyCapsule_GetName.restype = [c.py_object], c.c_char_p
    api.PyCapsule_GetPointer.argtypes, api.PyCapsule_GetPointer.restype = [c.py_object, c.c_char_p], c.c_void_p
    ptr = api.PyCapsule_GetPointer(model._cmodel, api.PyCapsule_GetName(model._cmodel))
    u64 = lambda p: c.c_uint64.from_address(p).value
    st = u64(ptr + 0xe8)
    # The API canonicalizes negative-zero bounds; restore their captured bits.
    for off, key in ((0x390, 'lb'), (0x398, 'ub')):
        base = u64(st + off)
        for j, bound in enumerate(d[key]):
            c.c_double.from_address(base + 8*j).value = bound
    assert same([v.Obj for v in vs], d['obj']) and same([v.LB for v in vs], d['lb'])
    assert same([v.UB for v in vs], d['ub']) and [v.VType for v in vs] == list(map(chr, d['vtype']))
    starts, lengths, indices, values = [u64(st + off) for off in (0xf8, 0x100, 0x108, 0x110)]
    # Public construction sorts columns by row; restore the captured order before CSR is built.
    for j in range(n):
        start = c.c_int64.from_address(starts + 8*j).value
        length = c.c_int.from_address(lengths + 4*j).value
        assert length == d['col_len'][j]
        for k in range(length):
            source = d['col_beg'][j] + k
            c.c_int.from_address(indices + 4*(start+k)).value = d['col_ind'][source]
            c.c_double.from_address(values + 8*(start+k)).value = d['col_val'][source]
        col = model.getCol(vs[j])
        source = d['col_beg'][j]
        assert [col.getConstr(k).index for k in range(col.size())] == d['col_ind'][source:source+length]
        assert same([col.getCoeff(k) for k in range(col.size())], d['col_val'][source:source+length])
    arr = c.c_double * n
    x, reference, lb, ub = arr(*d['x']), arr(*d['x']), arr(*d['lb']), arr(*d['ub'])
    vtype, rng = c.create_string_buffer(bytes(d['vtype'])), c.c_uint64(d['rng'])
    remaining, work = c.c_int(-1), c.c_double(0)
    budget = 100 * len(d['col_val']) + 100000
    status = func(1e100, budget, ptr, c.byref(rng), x, reference, vtype, lb, ub,
                  None, c.byref(remaining), 200, c.byref(work))
    for expected in (fixture['native'], fixture['rust']):
        assert same(x, expected['x']) and same(reference, expected['reference'])
        assert (remaining.value, work.value, rng.value) == (expected['remaining'], expected['work'], expected['rng'])
    assert status == fixture['native']['return'] == 0
    # Verify the row matrix generated by the native function, including order and bit patterns.
    rb, re, ri, rv = [u64(st + off) for off in (0x118, 0x120, 0x130, 0x138)]
    for i, row in enumerate(rows):
        begin, end = c.c_int64.from_address(rb+8*i).value, c.c_int64.from_address(re+8*i).value
        assert [c.c_int.from_address(ri+4*k).value for k in range(begin, end)] == [j for j, _ in row]
        assert same([c.c_double.from_address(rv+8*k).value for k in range(begin, end)], [a for _, a in row])
    objective = d['objcon'] + sum(a*b for a, b in zip(d['obj'], x))
    print(f'{name}: remaining={remaining.value}, work={work.value:g}, rng={rng.value}, objective={objective}')
    model.dispose()


def main():
    mapping = next(line for line in open('/proc/self/maps')
                   if 'libgurobi130.so' in line and line.split()[2] == '00000000')
    if gp.gurobi.version() != (13, 0, 3) or hashlib.sha256(Path(mapping.split()[-1]).read_bytes()).hexdigest() != HASH:
        raise SystemExit('unsupported Gurobi library: this fixture requires the verified 13.0.3 build')
    base = int(mapping.split('-')[0], 16)
    func = c.CFUNCTYPE(c.c_int, c.c_double, c.c_double, *([c.c_void_p]*9), c.c_int, c.c_void_p)(base + 0x74a5e0)
    mixed = gp.Model()
    mixed.Params.OutputFlag = 0
    mixed.addVar(vtype='B')
    mixed.addVar(vtype='I', lb=0, ub=3)
    mixed.addVar(vtype='C')
    mixed.update()
    api = c.pythonapi
    api.PyCapsule_GetName.argtypes, api.PyCapsule_GetName.restype = [c.py_object], c.c_char_p
    api.PyCapsule_GetPointer.argtypes, api.PyCapsule_GetPointer.restype = [c.py_object, c.c_char_p], c.c_void_p
    ptr = api.PyCapsule_GetPointer(mixed._cmodel, api.PyCapsule_GetName(mixed._cmodel))
    st = c.c_uint64.from_address(ptr + 0xe8).value
    assert (c.c_int.from_address(st + 0x2c).value, c.c_int.from_address(st + 0x30).value) == (2, 1)
    mixed.dispose()
    for name in sys.argv[1:] or ('sp150x300d', 'neos-3627168-kasai'):
        replay(name, func)


if __name__ == '__main__':
    main()
