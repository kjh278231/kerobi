"""Generate crates/model/src/param_table.rs from the parameter definition table in libgurobi130.so (docs/m1_driver.md §2).

The table is an array of 40-byte records in .data: name pointer (+0, relocated), flags (+8, int), type (+12, int:
1 int, 2 double, 3 string, -1 marker), min/max/default (+16/+24/+32, double). It starts at "Cutoff", has public
parameters up to the marker "EndPublic", then the hidden GURO_PAR_* ones, and ends with "End". `ac81d7` only binds
each name to its env offset; values come from here.
usage: python3 -I tools/param_table.py <libgurobi130.so> > crates/model/src/param_table.rs
"""
import struct
import sys

so = open(sys.argv[1], "rb").read()
shoff, = struct.unpack_from("<Q", so, 0x28)
shentsize, shnum, shstrndx = struct.unpack_from("<HHH", so, 0x3a)
secs = [struct.unpack_from("<IIQQQQIIQQ", so, shoff + i * shentsize) for i in range(shnum)]
strtab = secs[shstrndx][4]
sec = {so[strtab + s[0]:so.index(b"\0", strtab + s[0])].decode(): s for s in secs}


def file_off(va):
    for s in secs:
        if s[3] <= va < s[3] + s[5] and s[1] != 8:  # not SHT_NOBITS
            return va - s[3] + s[4]
    raise ValueError(hex(va))


def cstr(va):
    o = file_off(va)
    return so[o:so.index(b"\0", o)].decode()


rela, ptr = sec[".rela.dyn"], {}
for k in range(rela[5] // 24):
    off, info, addend = struct.unpack_from("<QQq", so, rela[4] + 24 * k)
    if info & 0xffffffff == 8:  # R_X86_64_RELATIVE
        ptr[off] = addend
# the record of "IterationLimit" (a name that occurs once), one record after the first one ("Cutoff")
name_va = so.index(b"\0IterationLimit\0") + 1 - sec[".rodata"][4] + sec[".rodata"][3]
rec = next(o for o, a in ptr.items() if a == name_va) - 40
rows = []
while True:
    name = cstr(ptr[rec])
    if name == "End":
        break
    typ, = struct.unpack_from("<i", so, file_off(rec) + 12)
    lo, hi, df = struct.unpack_from("<ddd", so, file_off(rec) + 16)
    if name != "EndPublic":
        rows.append((name, typ, lo, hi, df))
    rec += 40
assert len(rows) == 548 and rows[0][0] == "Cutoff", len(rows)

kind = {1: "Int", 2: "Dbl", 3: "Str"}
print("// Generated by tools/param_table.py from the libgurobi130.so parameter definition table; do not edit.")
print("// Order is the original table order: public parameters, then the hidden GURO_PAR_* ones.")
print("use crate::params::{Def, Kind::*};")
print()
print("pub const PARAMS: &[Def] = &[")
for name, typ, lo, hi, df in rows:
    print(f"    Def {{ name: {name!r}, kind: {kind[typ]}, min: {lo!r}, max: {hi!r}, default: {df!r} }},".replace("'", '"'))
print("];")
